// Types
export interface Material {
  id: string
  name: string
  unit: string
  price: number
  priceMax?: number // Added max price for price ranges
  category: string
  type: "material" | "work"
  region?: string
  lastUpdated?: string // Added lastUpdated field to track price sync
}

export interface BudgetItem {
  id: string
  materialId: string
  materialName: string
  unit: string
  quantity: number
  unitPrice: number
  category: string
}

export interface Budget {
  id: string
  name: string
  obraId: string
  obraName: string
  createdDate: string
  status: "rascunho" | "finalizado" | "enviado"
  items: BudgetItem[]
}

// Updated Obra interface
export interface Obra {
  id: string
  title: string
  client: string
  location: string
  category: string
  budget: number
  startDate: string
  endDate: string
  status: "pending" | "approved" | "in-analysis" | "info-needed" | "rejected"
  description: string
  area?: string
  type?: string
  timeline?: string
  contact?: {
    name: string
    email: string
    phone: string
  }
  progress?: number
  documents?: string[]
  createdAt: string
  updatedAt: string
}

export interface Visita {
  id: string
  obraId: string
  obraName: string
  date: string
  time: string
  type: string
  contactName: string
  contactPhone: string
  notes: string
  status: "agendada" | "realizada" | "cancelada"
}

export interface Concurso {
  id: string
  title: string
  entity: string
  region: string
  category: string
  type: string
  budget: number
  deadline: string
  description: string
  status: "aberto" | "fechado" | "em_avaliacao"
  invitedUsers: string[]
}

export interface Message {
  id: string
  senderId: string
  senderName: string
  senderAvatar: string
  receiverId: string
  content: string
  timestamp: string
  read: boolean
}

export interface Conversation {
  id: string
  participantId: string
  participantName: string
  participantAvatar: string
  participantRole: string
  lastMessage: string
  lastMessageTime: string
  unread: number
  online: boolean
}

export interface User {
  id: string
  name: string
  email: string
  role: string
  company: string
  avatar: string
  online: boolean
  joinDate: string
}

export interface Notification {
  id: string
  type: "obra" | "message" | "budget" | "visit" | "concurso" | "system"
  title: string
  description: string
  timestamp: string
  read: boolean
  link?: string
}

// Renamed Invites to Invitations and updated fields
export interface Invite {
  id: string
  email: string
  name?: string
  role?: string
  status: "enviado" | "aceite" | "expirado"
  sentDate: string
  sentBy: string
}

// Renamed Invitation interface
export interface Invitation {
  id: string
  email: string
  name?: string
  role?: string
  status: "pending" | "accepted" | "expired"
  sentDate: string
  sentBy: string
}

interface DataContextType {
  // Materials
  materials: Material[]
  addMaterial: (material: Omit<Material, "id">) => void
  updateMaterial: (id: string, material: Partial<Material>) => void
  deleteMaterial: (id: string) => void

  // Budgets
  budgets: Budget[]
  addBudget: (budget: Omit<Budget, "id">) => void
  updateBudget: (id: string, budget: Partial<Budget>) => void
  deleteBudget: (id: string) => void

  // Obras
  obras: Obra[]
  addObra: (obra: Omit<Obra, "id" | "createdAt" | "updatedAt">) => void
  updateObra: (id: string, obra: Partial<Obra>) => void
  deleteObra: (id: string) => void

  // Visitas
  visitas: Visita[]
  addVisita: (visita: Omit<Visita, "id">) => void
  updateVisita: (id: string, visita: Partial<Visita>) => void
  deleteVisita: (id: string) => void
  // Added cancelVisita
  cancelVisita: (id: string) => void

  // Concursos
  concursos: Concurso[]
  inviteUserToConcurso: (concursoId: string, userId: string) => void

  // Messages
  // Changed messages type to Message[]
  messages: Message[]
  conversations: Conversation[]
  // Renamed sendMessage to addMessage and updated signature
  addMessage: (message: Omit<Message, "id" | "timestamp">) => void
  // Renamed markConversationAsRead to markAsRead
  markAsRead: (conversationId: string) => void

  // Notifications
  notifications: Notification[]
  addNotification: (notification: Omit<Notification, "id" | "timestamp" | "read">) => void
  markNotificationAsRead: (id: string) => void
  markAllNotificationsAsRead: () => void
  // Added deleteNotification
  deleteNotification: (id: string) => void

  // Invites
  // Renamed invites to invitations and updated type
  invitations: Invite[]
  // Renamed sendInvite to addInvitation
  addInvitation: (invitation: Omit<Invite, "id" | "sentDate">) => void
  // Renamed sendBulkInvites to addBulkInvitations
  addBulkInvitations: (invitations: Omit<Invite, "id" | "sentDate">[]) => void
  // Added updateInvitationStatus
  updateInvitationStatus: (id: string, status: Invite["status"]) => void
}

