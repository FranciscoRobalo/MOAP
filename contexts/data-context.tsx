const initialObras: Obra[] = []

const initialBudgets: Budget[] = []

const initialVisitas: Visita[] = []

const initialConcursos: Concurso[] = []

const initialUsers: User[] = []

const initialConversations: Conversation[] = []

const initialMessages: Message[] = []

const initialNotifications: Notification[] = []

const initialInvitations: Invite[] = []

export function DataProvider({ children }: { children: ReactNode }) {
  const [materials, setMaterials] = useState<Material[]>(initialMaterials)
  const [budgets, setBudgets] = useState<Budget[]>(initialBudgets)
  const [obras, setObras] = useState<Obra[]>(initialObras)
  const [visitas, setVisitas] = useState<Visita[]>(initialVisitas)
  const [concursos, setConcursos] = useState<Concurso[]>(initialConcursos)
  const [users] = useState<User[]>(initialUsers)
  const [conversations, setConversations] = useState<Conversation[]>(initialConversations)
  // Changed messages state to Message[]
  const [messages, setMessages] = useState<Message[]>(initialMessages)
  const [notifications, setNotifications] = useState<Notification[]>(initialNotifications)
  // Renamed invites to invitations
  const [invitations, setInvitations] = useState<Invite[]>(initialInvitations)

  // Tracks whether the initial DB load has completed (prevents the
  // localStorage-save effect from overwriting cache before data arrives)
  const [isHydrated, setIsHydrated] = useState(false)

  // LOAD ALL DATA FROM DATABASE ON MOUNT
  useEffect(() => {
    let cancelled = false

    // 1. Optimistically hydrate from localStorage cache for instant UI
    const stored = localStorage.getItem("moap_data")
    if (stored) {
      try {
        const data = JSON.parse(stored)
        if (data.budgets) setBudgets(data.budgets)
        if (data.obras) setObras(data.obras)
        if (data.visitas) setVisitas(data.visitas)
        if (data.notifications) setNotifications(data.notifications)
        if (data.invitations) setInvitations(data.invitations)
      } catch (e) {
        console.error("Error loading cached data:", e)
      }
    }

    // 2. Load authoritative data from the database via the sync endpoint
    const loadFromDB = async () => {
      try {
        const response = await fetch("/api/data/sync")
        if (!response.ok) throw new Error(`sync failed: ${response.status}`)

        const result = await response.json()
        if (cancelled || !result?.success || !result.data) return

        const d = result.data
        console.log(
          "[v0] Loaded from DB - materials:", d.materials?.length || 0,
          "budgets:", d.budgets?.length || 0,
          "obras:", d.obras?.length || 0,
          "visitas:", d.visitas?.length || 0,
        )

        if (Array.isArray(d.materials) && d.materials.length > 0) setMaterials(d.materials)
        if (Array.isArray(d.budgets)) setBudgets(d.budgets)
        if (Array.isArray(d.obras)) setObras(d.obras)
        if (Array.isArray(d.visitas)) setVisitas(d.visitas)
        if (Array.isArray(d.notifications)) setNotifications(d.notifications)
      } catch (error) {
        console.log("[v0] DB sync unavailable, falling back to /api/materials + cache:", error)
        // Fallback: at least load the global materials reference list
        try {
          const matRes = await fetch("/api/materials")
          if (matRes.ok && !cancelled) {
            const matData = await matRes.json()
            if (matData.materials?.length > 0) setMaterials(matData.materials)
          }
        } catch {
          // Keep initial materials
        }
      } finally {
        if (!cancelled) setIsHydrated(true)
      }
    }

    loadFromDB()

    return () => {
      cancelled = true
    }
  }, [])

  // Persist a mutation to the database via the sync endpoint (best-effort).
  // Falls back silently to localStorage-only when the user is not authenticated.
  const persistToDB = async (type: string, data: unknown) => {
    try {
      const res = await fetch("/api/data/sync", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ type, data }),
      })
      if (!res.ok && res.status !== 401) {
        console.log(`[v0] persistToDB(${type}) failed:`, res.status)
      }
    } catch (error) {
      console.log(`[v0] persistToDB(${type}) error:`, error)
    }
  }

  // Save to localStorage on change (offline cache) — only after initial DB load
  useEffect(() => {
    if (!isHydrated) return
    localStorage.setItem(
      "moap_data",
      JSON.stringify({ materials, budgets, obras, visitas, notifications, invitations }),
    )
  }, [isHydrated, materials, budgets, obras, visitas, notifications, invitations])

  const generateId = () => Math.random().toString(36).substr(2, 9)

  // Materials
  const addMaterial = (material: Omit<Material, "id">) => {
    const newMaterial = { ...material, id: generateId() }
    setMaterials((prev) => [...prev, newMaterial])
    persistToDB("material", newMaterial)
    addNotification({
      type: "system",
      title: "Material Adicionado",
      description: `${material.name} foi adicionado à lista.`,
    })
  }

  const updateMaterial = (id: string, material: Partial<Material>) => {
    setMaterials((prev) => {
      const next = prev.map((m) => (m.id === id ? { ...m, ...material } : m))
      const updated = next.find((m) => m.id === id)
      if (updated) persistToDB("material", updated)
      return next
    })
  }

  const deleteMaterial = (id: string) => {
    setMaterials((prev) => prev.filter((m) => m.id !== id))
    persistToDB("delete", { table: "materials", id })
  }

  // Import budget items to materials database
  const importBudgetItems = (items: Array<{ name: string; unit: string; quantity: number; price: number }>, category: string = "Importado"): number => {
    let importedCount = 0
    const today = new Date().toISOString().split("T")[0]
    
    // Normalize text for comparison
    const normalizeText = (text: string): string => {
      return text
        .toLowerCase()
        .normalize("NFD")
        .replace(/[\u0300-\u036f]/g, "")
        .replace(/[^a-z0-9\s]/g, " ")
        .replace(/\s+/g, " ")
        .trim()
    }
    
    items.forEach(item => {
      if (!item.name || item.price <= 0) return
      
      const normalizedItemName = normalizeText(item.name)
      
      // Check if similar material already exists
      const existingMaterial = materials.find(m => {
        const normalizedMaterialName = normalizeText(m.name)
        // Check for exact match or high similarity
        return normalizedMaterialName === normalizedItemName ||
          normalizedMaterialName.includes(normalizedItemName) ||
          normalizedItemName.includes(normalizedMaterialName)
      })
      
      if (existingMaterial) {
        // Update existing material with new price data
        const newMinPrice = Math.min(existingMaterial.price, item.price)
        const newMaxPrice = Math.max(existingMaterial.priceMax || existingMaterial.price, item.price)
        
        setMaterials(prev => prev.map(m => 
          m.id === existingMaterial.id 
            ? { 
                ...m, 
                price: newMinPrice, 
                priceMax: newMaxPrice,
                lastUpdated: today 
              } 
            : m
        ))
      } else {
        // Add new material
        const newMaterial: Material = {
          id: generateId(),
          name: item.name.trim(),
          unit: item.unit || "un",
          price: item.price,
          priceMax: item.price * 1.2, // Set max 20% higher by default
          category: category,
          type: "work",
          region: "Nacional",
          lastUpdated: today
        }
        
        setMaterials(prev => [...prev, newMaterial])
        importedCount++
      }
    })
    
    if (importedCount > 0) {
      addNotification({
        type: "system",
        title: "Itens Importados",
        description: `${importedCount} novos itens foram adicionados à base de dados de materiais.`
      })
    }
    
    return importedCount
  }

  // Budgets
  const addBudget = (budget: Omit<Budget, "id">) => {
    const newBudget = { ...budget, id: generateId() }
    setBudgets((prev) => [...prev, newBudget])
    persistToDB("budget", newBudget)
    addNotification({ type: "budget", title: "Orçamento Criado", description: `${budget.name} foi criado.` })
  }

  const updateBudget = (id: string, budget: Partial<Budget>) => {
    setBudgets((prev) => {
      const next = prev.map((b) => (b.id === id ? { ...b, ...budget } : b))
      const updated = next.find((b) => b.id === id)
      if (updated) persistToDB("budget", updated)
      return next
    })
  }

  const deleteBudget = (id: string) => {
    setBudgets((prev) => prev.filter((b) => b.id !== id))
    persistToDB("delete", { table: "budgets", id })
  }

  // Obras
  const addObra = (obra: Omit<Obra, "id" | "createdAt" | "updatedAt">) => {
    const newObra: Obra = {
      ...obra,
      id: generateId(),
      // Updated default status and timestamps
      status: "pending",
      progress: 0,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    }
    setObras((prev) => [...prev, newObra])
    persistToDB("obra", newObra)
    addNotification({
      type: "obra",
      title: "Nova Obra Submetida",
      description: `${obra.title} foi submetida para análise.`,
    })
  }

  const updateObra = (id: string, obra: Partial<Obra>) => {
    setObras((prev) => {
      const next = prev.map((o) => (o.id === id ? { ...o, ...obra, updatedAt: new Date().toISOString() } : o))
      const updated = next.find((o) => o.id === id)
      if (updated) persistToDB("obra", updated)
      return next
    })
  }

  const deleteObra = (id: string) => {
    setObras((prev) => prev.filter((o) => o.id !== id))
    persistToDB("delete", { table: "obras", id })
  }

  // Visitas
  const addVisita = (visita: Omit<Visita, "id">) => {
    // Removed default status from here, it's handled in the UI or by initial data
    const newVisita: Visita = { ...visita, id: generateId() }
    setVisitas((prev) => [...prev, newVisita])
    persistToDB("visita", newVisita)
    addNotification({
      type: "visit",
      title: "Visita Agendada",
      description: `Visita a ${visita.obraName} agendada para ${visita.date}.`,
    })
  }

  const updateVisita = (id: string, visita: Partial<Visita>) => {
    setVisitas((prev) => {
      const next = prev.map((v) => (v.id === id ? { ...v, ...visita } : v))
      const updated = next.find((v) => v.id === id)
      if (updated) persistToDB("visita", updated)
      return next
    })
  }

  const deleteVisita = (id: string) => {
    setVisitas((prev) => prev.filter((v) => v.id !== id))
    persistToDB("delete", { table: "visitas", id })
  }

  // Added cancelVisita
  const cancelVisita = (id: string) => {
    setVisitas((prev) => {
      const next = prev.map((v) => (v.id === id ? { ...v, status: "cancelada" } : v))
      const updated = next.find((v) => v.id === id)
      if (updated) persistToDB("visita", updated)
      return next
    })
    addNotification({
      type: "visit",
      title: "Visita Cancelada",
      description: `A visita com o ID ${id} foi cancelada.`,
    })
  }

  // Concursos
  const inviteUserToConcurso = (concursoId: string, userId: string) => {
    setConcursos((prev) =>
      prev.map((c) => (c.id === concursoId ? { ...c, invitedUsers: [...c.invitedUsers, userId] } : c)),
    )
    const concurso = concursos.find((c) => c.id === concursoId)
    const user = users.find((u) => u.id === userId)
    if (concurso && user) {
      addNotification({
        type: "concurso",
        title: "Convite Enviado",
        description: `${user.name} foi convidado para ${concurso.title}.`,
      })
    }
  }

  // Messages
  // Renamed sendMessage to addMessage
  const addMessage = (message: Omit<Message, "id" | "timestamp">) => {
    const newMessage: Message = {
      ...message,
      id: generateId(),
      timestamp: new Date().toISOString(),
      read: false, // New messages are initially unread by the receiver
    }

    // Find the conversation this message belongs to
    let conversationId = ""
    // Assuming "1" is the current user's ID. This should be dynamically determined.
    // For now, hardcoding to simulate sender/receiver logic.
    const currentUserId = "1"
    if (message.senderId === currentUserId) {
      conversationId = conversations.find((c) => c.participantId === message.receiverId)?.id || ""
    } else {
      conversationId = conversations.find((c) => c.participantId === message.senderId)?.id || ""
    }

    setMessages((prev) => [...prev, newMessage])

    // Update conversation if it exists
    if (conversationId) {
      setConversations((prev) =>
        prev.map((c) =>
          c.id === conversationId
            ? {
                ...c,
                lastMessage: message.content,
                lastMessageTime: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
                // Increment unread count only if the receiver is the current user and is offline
                unread: c.participantId === currentUserId && !c.online ? c.unread + 1 : c.unread,
              }
            : c,
        ),
      )
    } else {
      // If conversation doesn't exist, create a new one (simplified)
      // This logic might need to be more robust, depending on how conversations are managed
      const participant = users.find((u) => u.id === message.receiverId || u.id === message.senderId)
      if (participant) {
        const newConversation: Conversation = {
          id: `conv-${generateId()}`,
          participantId: participant.id === currentUserId ? message.receiverId : message.senderId,
          participantName: participant.name,
          participantAvatar: participant.avatar,
          participantRole: participant.role,
          lastMessage: message.content,
          lastMessageTime: new Date().toLocaleTimeString([], { hour: "2-digit", minute: "2-digit" }),
          unread: 1, // New conversation, message is unread
          online: participant.online ?? false,
        }
        setConversations((prev) => [...prev, newConversation])
      }
    }
  }

  // Renamed markConversationAsRead to markAsRead
  const markAsRead = (conversationId: string) => {
    // Find the conversation to update
    const conversationToUpdate = conversations.find((c) => c.id === conversationId)

    if (conversationToUpdate) {
      // Update the conversation object in the state
      setConversations((prev) => prev.map((c) => (c.id === conversationId ? { ...c, unread: 0 } : c)))

      // Update messages associated with this conversation to mark them as read
      // Assuming senderId '1' is the current user
      const currentUserId = "1"
      setMessages((prev) =>
        prev.map((m) =>
          // Check if the message belongs to the conversation and is from the other participant
          m.id.startsWith("m") && // Basic check for message ID format
          ((m.senderId === conversationToUpdate.participantId && m.receiverId === currentUserId) ||
            (m.senderId === currentUserId && m.receiverId === conversationToUpdate.participantId)) &&
          m.read === false // Only update if it's currently unread
            ? { ...m, read: true }
            : m,
        ),
      )
    }
  }

  // Notifications
  const addNotification = (notification: Omit<Notification, "id" | "timestamp" | "read">) => {
    const newNotification: Notification = {
      ...notification,
      id: generateId(),
      timestamp: new Date().toISOString(),
      read: false,
    }
    setNotifications((prev) => [newNotification, ...prev])
    persistToDB("notification", newNotification)
  }

  const markNotificationAsRead = (id: string) => {
    setNotifications((prev) => prev.map((n) => (n.id === id ? { ...n, read: true } : n)))
    persistToDB("mark_notification_read", { id })
  }

  const markAllNotificationsAsRead = () => {
    setNotifications((prev) => {
      prev.forEach((n) => { if (!n.read) persistToDB("mark_notification_read", { id: n.id }) })
      return prev.map((n) => ({ ...n, read: true }))
    })
  }

  // Added deleteNotification
  const deleteNotification = (id: string) => {
    setNotifications((prev) => prev.filter((n) => n.id !== id))
    persistToDB("delete_notification", { id })
  }

  const clearNotifications = () => {
    setNotifications([])
  }

  // Invites
  // Renamed sendInvite to addInvitation
  const addInvitation = (invitation: Omit<Invite, "id" | "sentDate">) => {
    const newInvitation: Invite = {
      ...invitation,
      id: generateId(),
      sentDate: new Date().toISOString().split("T")[0],
      status: "enviado", // Default status
    }
    setInvitations((prev) => [...prev, newInvitation])
    addNotification({
      type: "system",
      title: "Convite Enviado",
      description: `Convite enviado para ${invitation.email}.`,
    })
  }

  // Renamed sendBulkInvites to addBulkInvitations
  const addBulkInvitations = (invitationsData: Omit<Invite, "id" | "sentDate">[]) => {
    const newInvitations = invitationsData.map((inv) => ({
      ...inv,
      id: generateId(),
      sentDate: new Date().toISOString().split("T")[0],
      status: "enviado" as const,
    }))
    setInvitations((prev) => [...prev, ...newInvitations])
    addNotification({
      type: "system",
      title: "Convites Enviados",
      description: `${invitationsData.length} convites enviados.`,
    })
  }

  // Added updateInvitationStatus
  const updateInvitationStatus = (id: string, status: Invite["status"]) => {
    setInvitations((prev) => prev.map((inv) => (inv.id === id ? { ...inv, status } : inv)))
  }

  return (
    <DataContext.Provider
      value={{
        materials,
        addMaterial,
        updateMaterial,
        deleteMaterial,
        importBudgetItems,
        budgets,
        addBudget,
        updateBudget,
        deleteBudget,
        obras,
        addObra,
        updateObra,
        deleteObra,
        visitas,
        addVisita,
        updateVisita,
        deleteVisita,
        cancelVisita, // Added cancelVisita
        concursos,
        inviteUserToConcurso,
        conversations,
        messages, // Changed messages state
        addMessage, // Renamed sendMessage
        markAsRead, // Renamed markConversationAsRead
        users,
        notifications,
        addNotification,
        markNotificationAsRead,
        markAllNotificationsAsRead,
        deleteNotification, // Added deleteNotification
        clearNotifications, // Added clearNotifications
        invitations, // Renamed invites
        addInvitation, // Renamed sendInvite
        addBulkInvitations, // Renamed sendBulkInvites
        updateInvitationStatus, // Added updateInvitationStatus
      }}
    >
      {children}
    </DataContext.Provider>
  )
}

export function useData() {
  const context = useContext(DataContext)
  if (context === undefined) {
    throw new Error("useData must be used within a DataProvider")
  }
  return context
}
